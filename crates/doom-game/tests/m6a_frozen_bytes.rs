//! M6a part 2: byte pins for the four formats part 1 froze.
//!
//! Part 1 froze `DSIM` 42 (doom-sim), `DDSP` version 3 (doom-render's session display), `DSND`
//! version 2 (doom-sound's `ChainSound`) and `DSES` version 1 (doom-game's session save). Part 2
//! adds second configurations beside them and must prove the frozen ones still write the same
//! bytes. `tests/reference/m6a_state.txt` pins `DSIM` 42 captures only without their `map.*` and
//! `events.*` fields, and nothing committed pinned the full bytes of the other three, so this
//! test does: it drives the frozen part 1 session (`Session::new`, no finale, no melt) over a set
//! of committed items at screenblocks 10 and 11 and hashes, at declared points, the full encoded
//! bytes of each of
//!
//! - `DSES` v1: `Session::save()?.encode()`;
//! - `DDSP` v3: `SessionState::display.encode()` (the display's own writer, embedded as the
//!   `display` blob of `DSES`);
//! - `DSND` v2: `SessionState::sound.encode()` (the sound's own writer, the `sound` blob);
//! - `DSIM` 42: `SessionState::level`, the level's `canonical_bytes()` (the `level` blob).
//!
//! The three components are the very values `DSES` embeds, taken from the public fields of
//! [`SessionState`], so no layout is re-parsed here.
//!
//! The fixture `tests/reference/m6a_frozen_bytes.txt` was generated by this same file run on
//! master at 25cdb3ba (before part 2) in a scratch worktree (docs/TESTING.md); it is not an
//! original-C expectation but a regression pin of bytes already accepted in part 1: a digest that
//! differs on a later branch means a frozen format changed. Only APIs that exist on master are
//! used, so the file runs there unchanged.
//!
//! The points of an item at one screenblocks: the start (before any tic), every load tic, every
//! tic after which `gamestate`, `map` or `gameaction` changed, every tic after which `gametic`
//! is a multiple of 35, and the last tic (the demo's end, or the tic whose refusal ended the
//! item, the session unchanged). A point holds all four formats; its rows are named by the
//! `why` list.
//!
//! Set `M6A_FROZEN_BYTES_WRITE=/absolute/path` to write the fixture there instead of comparing.
mod m6a;

use doom_game::session::demo::SessionDemo;
use doom_game::session::{Session, SessionSettings, TicKind};
use doom_test_evidence::sha256;
use std::fmt::Write as _;

/// The items: levels with carried players, held reborn, the secret level, turbo, attack, the
/// dead reborn, and the E1M8 finale item (run to its `NotYet::Victory` refusal).
const ITEMS: [&str; 10] = [
    "CHAIN", "REBHELD", "SECRET", "TURBO", "ATTACK", "REBSECRT", "RBXDEAD", "SKILL3", "INTCMD",
    "FINREG",
];

const STRIDE: u64 = 35;

const HEADER: &str = "\
#schema,DOOM-M6A-FROZEN-BYTES-v1
#generator,crates/doom-game/tests/m6a_frozen_bytes.rs run on master at 25cdb3ba (part 1, before the finale and melt) in a scratch worktree with M6A_FROZEN_BYTES_WRITE; a regression pin of accepted bytes, not an original-C expectation
#bytes,len and SHA-256 of the full encoded bytes: DSES = Session::save().encode(); DDSP, DSND, DSIM42 = the display, sound and level blobs DSES embeds (SessionState fields display.encode(), sound.encode(), level)
#points,start (gametic 0), each load tic, each tic after which gamestate, map or gameaction changed, every gametic multiple of 35, the last tic (demo end or the refusal that ended the item)
#columns,R,item,screenblocks,gametic,why,format,len,sha256
#columns,Q,item,screenblocks,rows,bytes,sequence_sha256 (SHA-256 of the item's R lines, each ending in LF)
";

/// The four formats' rows of the session's saved state.
fn rows_of(item: &str, sb: u8, session: &Session, why: &str, out: &mut Vec<String>) {
    let state = session.save().unwrap_or_else(|e| {
        panic!(
            "{item} sb{sb} gametic {}: save failed {e:?}",
            session.gametic()
        )
    });
    let parts: [(&str, Vec<u8>); 4] = [
        ("DSES", state.encode()),
        ("DDSP", state.display.encode()),
        ("DSND", state.sound.encode()),
        ("DSIM42", state.level.clone()),
    ];
    for (format, bytes) in parts {
        out.push(format!(
            "R,{item},{sb},{},{why},{format},{},{}",
            session.gametic(),
            bytes.len(),
            sha256(&bytes)
        ));
    }
}

/// The rows of one item at one screenblocks, then its `Q` line.
fn run(item_name: &str, sb: u8) -> Vec<String> {
    let item = m6a::item(item_name);
    let data = m6a::data(&item, None);
    let lmp = std::fs::read(m6a::root(&item.lmp)).expect("demo");
    let demo = SessionDemo::parse(&lmp).expect("demo");
    let mut session = Session::new(
        data,
        SessionSettings {
            map: item.map,
            skill: item.skill,
            screenblocks: sb,
        },
    )
    .unwrap_or_else(|e| panic!("{item_name}: start {e:?}"));
    let key = |s: &Session| (format!("{:?}", s.gamestate()), s.map(), s.gameaction());
    let mut rows = Vec::new();
    rows_of(item_name, sb, &session, "start", &mut rows);
    let mut prev = key(&session);
    let mut ended = false;
    let mut last_tic = demo.commands.len();
    for (t, &cmd) in demo.commands.iter().enumerate() {
        let report = match session.tic(cmd) {
            Ok(r) => r,
            Err(_) => {
                // The refusal keeps the session: the last point is the unchanged state.
                ended = true;
                last_tic = t;
                break;
            }
        };
        let now = key(&session);
        let mut why = Vec::new();
        if matches!(report.kind, TicKind::Load { .. }) {
            why.push("load");
        }
        if now != prev {
            why.push("change");
        }
        if session.gametic() % STRIDE == 0 {
            why.push("stride");
        }
        if t + 1 == demo.commands.len() {
            why.push("last");
        }
        prev = now;
        if !why.is_empty() {
            rows_of(item_name, sb, &session, &why.join("+"), &mut rows);
        }
    }
    if ended {
        rows_of(item_name, sb, &session, "last+refused", &mut rows);
    }
    assert!(
        !ended || item_name == "FINREG",
        "{item_name}: only the finale item may end in a refusal (tic {last_tic})"
    );
    let bytes: u64 = rows
        .iter()
        .map(|r| r.split(',').nth(6).unwrap().parse::<u64>().unwrap())
        .sum();
    let mut text = String::new();
    for r in &rows {
        writeln!(text, "{r}").unwrap();
    }
    let n = rows.len();
    rows.push(format!(
        "Q,{item_name},{sb},{n},{bytes},{}",
        sha256(text.as_bytes())
    ));
    rows
}

/// Compares two line lists; the error names the item, screenblocks, gametic and format of the
/// first row that differs.
fn compare(want: &[String], got: &[String]) -> Result<(), String> {
    for (i, g) in got.iter().enumerate() {
        let Some(w) = want.get(i) else {
            return Err(format!("extra row {i}: {g}"));
        };
        if w != g {
            let f: Vec<&str> = g.split(',').collect();
            let name = if f[0] == "R" {
                format!("item {} sb{} gametic {} format {}", f[1], f[2], f[3], f[5])
            } else {
                format!("item {} sb{} sequence line", f[1], f[2])
            };
            return Err(format!("{name} differs\n  pinned: {w}\n  now:    {g}"));
        }
    }
    if want.len() != got.len() {
        return Err(format!(
            "{} rows pinned, {} produced",
            want.len(),
            got.len()
        ));
    }
    Ok(())
}

fn all_rows() -> Vec<String> {
    let mut rows = Vec::new();
    for item in ITEMS {
        for sb in [10, 11] {
            rows.extend(run(item, sb));
        }
    }
    rows
}

/// The frozen `DSES` v1, `DDSP` v3, `DSND` v2 and `DSIM` 42 bytes of the part 1 session equal the
/// committed digests, for every item, screenblocks and point.
#[test]
fn the_frozen_formats_write_the_pinned_bytes() {
    let rows = all_rows();
    if let Some(path) = std::env::var_os("M6A_FROZEN_BYTES_WRITE") {
        let path = std::path::PathBuf::from(path);
        assert!(
            path.is_absolute(),
            "M6A_FROZEN_BYTES_WRITE must be absolute"
        );
        let mut text = HEADER.to_owned();
        for r in &rows {
            writeln!(text, "{r}").unwrap();
        }
        std::fs::write(&path, text).expect("write fixture");
        eprintln!("wrote {} rows to {}", rows.len(), path.display());
        return;
    }
    let text = std::fs::read_to_string(m6a::root("tests/reference/m6a_frozen_bytes.txt"))
        .expect("fixture");
    assert!(text.starts_with("#schema,DOOM-M6A-FROZEN-BYTES-v1\n"));
    let want: Vec<String> = text
        .lines()
        .filter(|l| !l.starts_with('#'))
        .map(str::to_owned)
        .collect();
    if let Err(e) = compare(&want, &rows) {
        panic!("{e}");
    }
    let hashed: u64 = rows
        .iter()
        .filter(|r| r.starts_with("R,"))
        .map(|r| r.split(',').nth(6).unwrap().parse::<u64>().unwrap())
        .sum();
    eprintln!("{} rows, {hashed} bytes hashed", rows.len());
}

/// Pins the comparison itself: one changed digest character fails and names the item,
/// screenblocks, gametic and format; a missing or extra row fails.
#[test]
fn a_changed_digest_fails_and_is_named() {
    let want: Vec<String> = vec![
        "R,CHAIN,10,35,stride,DDSP,100,aaaa".into(),
        "R,CHAIN,10,35,stride,DSND,200,bbbb".into(),
        "Q,CHAIN,10,2,300,cccc".into(),
    ];
    assert!(compare(&want, &want).is_ok());
    let mut got = want.clone();
    got[1] = "R,CHAIN,10,35,stride,DSND,200,bbbc".into();
    let e = compare(&want, &got).expect_err("differs");
    assert!(e.contains("item CHAIN sb10 gametic 35 format DSND"), "{e}");
    assert!(compare(&want, &want[..2]).is_err());
    let mut more = want.clone();
    more.push("Q,X,10,0,0,d".into());
    assert!(compare(&want, &more).is_err());
}
