pub(crate) fn registry_fields(fields: &mut Vec<StateField>, registry: &crate::ActorRegistry) {
    count(fields, "registry.states.count", registry.states.len());
    for (i, state) in registry.states.iter().enumerate() {
        let mut b = vec![state.name.len() as u8];
        b.extend(state.name.as_bytes());
        b.extend(state.sprite.to_le_bytes());
        b.extend(state.frame.to_le_bytes());
        b.extend(state.tics.to_le_bytes());
        action_bytes(&mut b, state.action);
        b.extend(state.next.0.to_le_bytes());
        for value in state.misc {
            b.extend(value.to_le_bytes());
        }
        field(fields, format!("registry.state.{i}"), b);
    }
    count(fields, "registry.types.count", registry.types.len());
    for (i, ty) in registry.types.iter().enumerate() {
        let mut b = vec![ty.name.len() as u8];
        b.extend(ty.name.as_bytes());
        for v in ty.properties {
            b.extend(v.to_le_bytes());
        }
        field(fields, format!("registry.type.{i}"), b);
    }
}

fn combat_bytes(b: &mut Vec<u8>, event: &crate::CombatEvent) {
    use crate::CombatEvent::*;
    fn object(b: &mut Vec<u8>, o: crate::TraceObject) {
        match o {
            crate::TraceObject::Line(i) => {
                b.push(0);
                b.extend(i.to_le_bytes());
            }
            crate::TraceObject::Actor(i) => {
                b.push(1);
                b.extend(id(i));
            }
        }
    }
    fn fixed(b: &mut Vec<u8>, v: doom_types::Fixed) {
        b.extend(v.bits().to_le_bytes());
    }
    match event {
        Attack { shooter, attack } => {
            b.push(0);
            b.extend(id(*shooter));
            b.extend(attack.angle.to_le_bytes());
            fixed(b, attack.range);
            fixed(b, attack.slope);
            b.extend(attack.damage.to_le_bytes());
        }
        Trace { result } => {
            b.push(1);
            for v in result.trace.origin.into_iter().chain(result.trace.delta) {
                fixed(b, v);
            }
            b.extend((result.trace.cells.len() as u32).to_le_bytes());
            for cell in &result.trace.cells {
                for v in cell {
                    b.extend(v.to_le_bytes());
                }
            }
            b.extend((result.trace.candidates.len() as u32).to_le_bytes());
            for o in &result.trace.candidates {
                object(b, *o);
            }
            b.extend((result.trace.intercepts.len() as u32).to_le_bytes());
            for i in &result.trace.intercepts {
                fixed(b, i.fraction);
                object(b, i.object);
            }
            b.push(u8::from(result.hit.is_some()));
            if let Some(hit) = result.hit {
                object(b, hit);
            }
            b.push(u8::from(result.position.is_some()));
            if let Some(p) = result.position {
                for v in p {
                    fixed(b, v);
                }
            }
            b.extend(result.traversed.to_le_bytes());
        }
        Damage(r) => {
            b.push(2);
            b.extend(id(r.target));
            b.extend(optional_id(r.inflictor));
            b.extend(optional_id(r.source));
            b.extend(r.amount.to_le_bytes());
        }
        Random { kind, value } => b.extend([3, *kind, *value]),
        Knockback {
            target,
            angle,
            thrust,
            momentum,
        } => {
            b.push(4);
            b.extend(id(*target));
            b.extend(angle.to_le_bytes());
            fixed(b, *thrust);
            for v in momentum {
                fixed(b, *v);
            }
        }
        Health { target, values } => {
            b.push(5);
            b.extend(id(*target));
            for v in values {
                b.extend(v.to_le_bytes());
            }
        }
        Pain { target, state } => {
            b.push(6);
            b.extend(id(*target));
            b.extend(state.0.to_le_bytes());
        }
        Kill {
            target,
            state,
            extreme,
        } => {
            b.push(7);
            b.extend(id(*target));
            b.extend(state.0.to_le_bytes());
            b.push(u8::from(*extreme));
        }
        DeathTimer { target, tics } => {
            b.push(8);
            b.extend(id(*target));
            b.extend(tics.to_le_bytes());
        }
        Reaction(target) => {
            b.push(9);
            b.extend(id(*target));
        }
        Retarget { target, source } => {
            b.push(10);
            b.extend(id(*target));
            b.extend(id(*source));
        }
        Impact { actor } => {
            b.push(11);
            b.extend(id(*actor));
        }
        Ignored(actor) => {
            b.push(12);
            b.extend(id(*actor));
        }
    }
}

