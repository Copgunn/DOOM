/// Named canonical field. Bytes use schema-defined widths and little-endian order.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct StateField {
    path: String,
    value: Vec<u8>,
}
impl StateField {
    /// Stable schema path, independent of allocator/platform details.
    pub fn path(&self) -> &str {
        &self.path
    }
    /// Explicit encoded value, never Rust struct layout or padding.
    pub fn value(&self) -> &[u8] {
        &self.value
    }
}
fn field(fields: &mut Vec<StateField>, path: impl Into<String>, value: impl Into<Vec<u8>>) {
    fields.push(StateField {
        path: path.into(),
        value: value.into(),
    });
}
fn id(value: ActorId) -> Vec<u8> {
    let mut b = value.slot().to_le_bytes().to_vec();
    b.extend(value.generation().to_le_bytes());
    b
}
fn optional_id(value: Option<ActorId>) -> Vec<u8> {
    let mut b = vec![u8::from(value.is_some())];
    b.extend(id(value.unwrap_or(ActorId::from_parts(0, 0))));
    b
}
fn count(fields: &mut Vec<StateField>, path: &str, value: usize) {
    field(fields, path, (value as u64).to_le_bytes());
}

/// Immutable per-tic state, sharing immutable map fields without encoding addresses.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Snapshot {
    version: u32,
    tic: u64,
    state: Vec<StateField>,
    map: Arc<Vec<StateField>>,
}
impl Snapshot {
    /// Explicit diagnostic schema version (1–26); field layouts are selected per profile.
    /// See the repository STATE_FORMAT guide for widths and composition.
    pub const fn version(&self) -> u32 {
        self.version
    }
    /// Completed logical tic attached to this capture.
    pub const fn tic(&self) -> u64 {
        self.tic
    }
    /// Stable ordered fields, runtime first then static map tables.
    pub fn fields(&self) -> impl Iterator<Item = &StateField> {
        self.state.iter().chain(self.map.iter())
    }
    /// DSIM + u32 format version + u64 field count, then each field as u32 UTF-8 path
    /// length/path/u64 value length/value. Integer values use little endian.
    /// Paths are generated by this bounded schema and fit u32; lengths fit u64
    /// on all supported hosts. No native-width integer is serialized directly.
    pub fn canonical_bytes(&self) -> Vec<u8> {
        let mut out = b"DSIM".to_vec();
        out.extend(self.version.to_le_bytes());
        out.extend(((self.state.len() + self.map.len()) as u64).to_le_bytes());
        for f in self.fields() {
            out.extend((f.path.len() as u32).to_le_bytes());
            out.extend(f.path.as_bytes());
            out.extend((f.value.len() as u64).to_le_bytes());
            out.extend(&f.value);
        }
        out
    }
    /// Stable FNV-1a-64 over canonical bytes. Noncryptographic and not an equivalence proof.
    pub fn digest(&self) -> u64 {
        self.canonical_bytes()
            .into_iter()
            .fold(0xcbf29ce484222325, |h, b| {
                (h ^ u64::from(b)).wrapping_mul(0x100000001b3)
            })
    }
    /// First differing named field. Compare bytes even when digests happen to match.
    pub fn first_difference(&self, actual: &Self) -> Option<Divergence> {
        if self.version != actual.version {
            return Some(Divergence {
                tic: self.tic,
                field: "schema.version".into(),
                expected: self.version.to_le_bytes().to_vec(),
                actual: actual.version.to_le_bytes().to_vec(),
            });
        }
        let mut expected = self.fields();
        let mut got = actual.fields();
        loop {
            match (expected.next(), got.next()) {
                (None, None) => return None,
                (Some(e), Some(a)) if e.path == a.path && e.value == a.value => {}
                (Some(e), Some(a)) => {
                    return Some(Divergence {
                        tic: self.tic,
                        field: if e.path == a.path {
                            e.path.clone()
                        } else {
                            format!("schema:{}", e.path)
                        },
                        expected: e.value.clone(),
                        actual: a.value.clone(),
                    });
                }
                (Some(e), None) => {
                    return Some(Divergence {
                        tic: self.tic,
                        field: e.path.clone(),
                        expected: e.value.clone(),
                        actual: Vec::new(),
                    });
                }
                (None, Some(a)) => {
                    return Some(Divergence {
                        tic: self.tic,
                        field: a.path.clone(),
                        expected: Vec::new(),
                        actual: a.value.clone(),
                    });
                }
            }
        }
    }
}

/// First divergent tic and field, with encoded values for private inspection.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Divergence {
    /// Expected logical tic at the first divergent capture.
    pub tic: u64,
    /// Stable named state field.
    pub field: String,
    /// Expected schema bytes.
    pub expected: Vec<u8>,
    /// Actual schema bytes.
    pub actual: Vec<u8>,
}
impl fmt::Display for Divergence {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "first divergence at tic {} field {}",
            self.tic, self.field
        )
    }
}

/// Compares whole traces in capture order, reporting the earliest differing field/tic.
pub fn compare_traces(expected: &[Snapshot], actual: &[Snapshot]) -> Option<Divergence> {
    for (e, a) in expected.iter().zip(actual) {
        if let Some(d) = e.first_difference(a) {
            return Some(d);
        }
    }
    if expected.len() != actual.len() {
        let i = expected.len().min(actual.len());
        return Some(Divergence {
            tic: expected
                .get(i)
                .or_else(|| actual.get(i))
                .map_or(0, Snapshot::tic),
            field: "trace.length".into(),
            expected: (expected.len() as u64).to_le_bytes().to_vec(),
            actual: (actual.len() as u64).to_le_bytes().to_vec(),
        });
    }
    None
}

fn actor_attempt_bytes(b: &mut Vec<u8>, actor: ActorId, attempt: &crate::ActorMoveAttempt) {
    b.extend(id(actor));
    for v in attempt.target {
        b.extend(v.bits().to_le_bytes());
    }
    b.extend(optional_id(attempt.blocked_by_actor));
    b.extend((attempt.actors.len() as u32).to_le_bytes());
    for a in &attempt.actors {
        b.extend(id(*a));
    }
    b.extend(attempt.lines.blocked_by.unwrap_or(u16::MAX).to_le_bytes());
    b.push(u8::from(attempt.lines.fits));
    b.extend((attempt.lines.candidates.len() as u32).to_le_bytes());
    for line in &attempt.lines.candidates {
        b.extend(line.to_le_bytes());
    }
}

fn event_bytes(event: &Event) -> Vec<u8> {
    let mut b = Vec::new();
    match event {
        Event::Armor(event) => {
            b.push(24);
            b.extend(id(event.target));
            b.extend(event.incoming.to_le_bytes());
            b.extend(event.saved.to_le_bytes());
            b.extend(event.effective.to_le_bytes());
            b.push(event.before.kind.wire_id());
            b.extend(event.before.points.to_le_bytes());
            b.push(event.after.kind.wire_id());
            b.extend(event.after.points.to_le_bytes());
        }
        Event::Pickup(event) => {
            use crate::PickupEvent::*;
            b.push(23);
            let pending =
                |w: Option<crate::Weapon>| w.map_or(crate::player_weapons::NO_CHANGE, |w| w as u8);
            match event {
                Touch(item, body, sprite, delta, height, health) => {
                    b.push(0);
                    b.extend(id(*item));
                    b.extend(id(*body));
                    b.extend(sprite.to_le_bytes());
                    b.extend(delta.bits().to_le_bytes());
                    b.extend(height.bits().to_le_bytes());
                    b.extend(health.to_le_bytes());
                }
                Ammo(ammo, accepted, before, after, ready, next) => {
                    b.extend([1, *ammo, u8::from(*accepted)]);
                    b.extend(before.to_le_bytes());
                    b.extend(after.to_le_bytes());
                    b.extend([*ready as u8, pending(*next)]);
                }
                Body(accepted, before, after, health) => {
                    b.extend([2, u8::from(*accepted)]);
                    b.extend(before.to_le_bytes());
                    b.extend(after.to_le_bytes());
                    b.extend(health.to_le_bytes());
                }
                Weapon(weapon, accepted, before, after, old, next) => {
                    b.extend([3, *weapon as u8, u8::from(*accepted)]);
                    b.extend(before.to_le_bytes());
                    b.extend(after.to_le_bytes());
                    b.extend([pending(*old), pending(*next)]);
                }
                Message(message) => b.extend([4, *message as u8]),
                Bonus(count, items) => {
                    b.push(5);
                    b.extend(count.to_le_bytes());
                    b.extend(items.to_le_bytes());
                }
                Result(item, outcome) => {
                    b.push(6);
                    b.extend(id(*item));
                    b.push(*outcome as u8);
                }
                Armor(requested, accepted, before, after) => {
                    b.extend([
                        7,
                        requested.wire_id(),
                        u8::from(*accepted),
                        before.kind.wire_id(),
                    ]);
                    b.extend(before.points.to_le_bytes());
                    b.push(after.kind.wire_id());
                    b.extend(after.points.to_le_bytes());
                }
            }
        }
        Event::PlayerBody(event) => {
            use crate::PlayerBodyEvent;
            b.push(22);
            match event {
                PlayerBodyEvent::Bound(body) => {
                    b.push(0);
                    b.extend(id(*body));
                }
                PlayerBodyEvent::Damaged {
                    health,
                    attacker,
                    damage_count,
                    tactile,
                } => {
                    b.push(1);
                    b.extend(health.to_le_bytes());
                    b.extend(optional_id(*attacker));
                    b.extend(damage_count.to_le_bytes());
                    b.extend(tactile.to_le_bytes());
                }
                PlayerBodyEvent::Died { frags, weapon_down } => {
                    b.push(2);
                    b.extend(frags.to_le_bytes());
                    b.extend(weapon_down.ordinal().to_le_bytes());
                }
            }
        }

        Event::Refire(event) => {
            b.extend([20, event.decision.code()]);
            b.extend(event.actor.slot().to_le_bytes());
            b.extend(event.actor.generation().to_le_bytes());
        }
        Event::Shotgun(event) => {
            b.push(19);
            crate::shotgunner::event_bytes(&mut b, event);
        }
        Event::Monster(event) => {
            b.push(18);
            crate::monsters::event_bytes(&mut b, event);
        }
        Event::Pursuit(event) => {
            b.push(17);
            crate::pursuit::event_bytes(&mut b, event);
        }
        Event::Perception(event) => {
            b.push(16);
            crate::perception::event_bytes(&mut b, event);
        }
        Event::Projectile(event) => {
            use crate::{ProjectileAim, ProjectileEvent};
            b.push(15);
            match event {
                ProjectileEvent::Exploded(actor) => {
                    b.push(0);
                    b.extend(id(*actor));
                }
                ProjectileEvent::Velocity {
                    actor,
                    angle,
                    momentum,
                } => {
                    b.push(1);
                    b.extend(id(*actor));
                    b.extend(angle.to_le_bytes());
                    for m in momentum {
                        b.extend(m.bits().to_le_bytes());
                    }
                }
                ProjectileEvent::Random { kind, value } => {
                    b.extend([2, *kind, *value]);
                }
                ProjectileEvent::HalfStep {
                    actor,
                    position,
                    tics,
                } => {
                    b.push(4);
                    b.extend(id(*actor));
                    for p in position {
                        b.extend(p.bits().to_le_bytes());
                    }
                    b.extend(tics.to_le_bytes());
                }
                ProjectileEvent::Launch(request) => {
                    b.push(5);
                    b.extend(id(request.source));
                    match request.aim {
                        ProjectileAim::Actor(target) => {
                            b.push(0);
                            b.extend(id(target));
                        }
                        ProjectileAim::PlayerAutoAim => b.push(1),
                    }
                    b.extend(request.actor_type.0.to_le_bytes());
                }
            }
        }
        Event::Weapon(event) => {
            b.push(14);
            weapon_bytes(&mut b, event);
        }
        Event::Combat(event) => {
            b.push(13);
            combat_bytes(&mut b, event);
        }
        Event::ActorState(event) => {
            b.push(12);
            state_event_bytes(&mut b, event);
        }
        Event::Phase(p) => b.extend([
            0,
            match p {
                Phase::Players => 0,
                Phase::Thinkers => 1,
                Phase::Specials => 2,
                Phase::Respawn => 3,
            },
        ]),
        Event::Spawned(a) => {
            b.push(1);
            b.extend(id(*a));
        }
        Event::RemovalMarked(a) => {
            b.push(2);
            b.extend(id(*a));
        }
        Event::Retired(a) => {
            b.push(3);
            b.extend(id(*a));
        }
        Event::Player { slot, actor } => {
            b.extend([4, *slot]);
            b.extend(id(*actor));
        }
        Event::Think(a) => {
            b.push(5);
            b.extend(id(*a));
        }
        Event::Movement { actor, attempt } => {
            b.push(6);
            b.extend(id(*actor));
            for x in attempt.target {
                b.extend(x.bits().to_le_bytes());
            }
            b.extend(
                attempt
                    .collision
                    .blocked_by
                    .unwrap_or(u16::MAX)
                    .to_le_bytes(),
            );
            b.push(u8::from(attempt.collision.fits));
            b.extend((attempt.collision.candidates.len() as u32).to_le_bytes());
            for c in &attempt.collision.candidates {
                b.extend(c.to_le_bytes());
            }
        }
        Event::Statistics(event) => {
            let (kind, actor, total) = match event {
                crate::StatisticsEvent::MapKillTotal { actor, total } => (0, *actor, *total),
                crate::StatisticsEvent::SinglePlayerKill { actor, total } => (1, *actor, *total),
            };
            b.extend([21, kind]);
            b.extend(id(actor));
            b.extend(total.to_le_bytes());
        }
        Event::GameplayRandom(v) => b.extend([7, *v]),
        Event::ActorMovement { actor, attempt } => {
            b.push(8);
            actor_attempt_bytes(&mut b, *actor, attempt);
        }
        Event::SectorMovement { actor, attempt } => {
            b.push(10);
            actor_attempt_bytes(&mut b, *actor, &attempt.movement);
            b.extend(attempt.location.subsector.to_le_bytes());
            b.extend(attempt.location.sector.to_le_bytes());
            for value in [attempt.floor, attempt.ceiling, attempt.dropoff] {
                b.extend(value.bits().to_le_bytes());
            }
            b.extend([u8::from(attempt.float_ok), attempt.failure as u8]);
            b.extend((attempt.openings.len() as u32).to_le_bytes());
            for visit in &attempt.openings {
                b.extend(visit.line.to_le_bytes());
                for value in [
                    visit.opening.top,
                    visit.opening.bottom,
                    visit.opening.range,
                    visit.opening.low_floor,
                ] {
                    b.extend(value.bits().to_le_bytes());
                }
            }
        }
        Event::Vertical { actor, update } => {
            b.push(11);
            b.extend(id(*actor));
            for value in update
                .before
                .into_iter()
                .chain(update.after)
                .chain(update.constraints)
            {
                b.extend(value.bits().to_le_bytes());
            }
            b.extend([
                u8::from(update.floor_contact),
                u8::from(update.ceiling_contact),
                u8::from(update.gravity_applied),
            ]);
        }
        Event::Slide { actor, line } => {
            b.push(9);
            b.extend(id(*actor));
            b.extend(line.to_le_bytes());
        }
    }
    b
}

#[cfg(test)]
std::thread_local! {
    static CAPTURES: std::cell::Cell<u64> = const { std::cell::Cell::new(0) };
}
#[cfg(test)]
pub(crate) fn capture_count() -> u64 {
    CAPTURES.with(std::cell::Cell::get)
}

pub(crate) fn capture(sim: &Simulation) -> Snapshot {
    #[cfg(test)]
    CAPTURES.with(|count| count.set(count.get().wrapping_add(1)));
    let mut fields = Vec::new();
    field(&mut fields, "tic", sim.tic.to_le_bytes());
    field(&mut fields, "tic_rate", doom_types::TIC_RATE.to_le_bytes());
    let version = match sim.profile {
        crate::Profile::Foundation => 1_u32,
        crate::Profile::PlayerCollision => 2,
        crate::Profile::MultiSector => 3,
        crate::Profile::ActorStates => 4,
        crate::Profile::Combat => 5,
        crate::Profile::PlayerWeapons => 6,
        crate::Profile::Projectiles => 7,
        crate::Profile::Perception => 8,
        crate::Profile::Pursuit => 9,
        crate::Profile::MonsterAttacks => 10,
        crate::Profile::Shotgunner => 11,
        crate::Profile::Chaingunner => 12,
        crate::Profile::DemonMelee => 13,
        crate::Profile::DemonLifecycle => 14,
        crate::Profile::DemonStandRun => 15,
        crate::Profile::DemonMapSpawn => 16,
        crate::Profile::DemonMapContext => 17,
        crate::Profile::MapScale => 18,
        crate::Profile::MapExtent => 19,
        crate::Profile::DemonExpandedMap => 20,
        crate::Profile::OriginalDemon => {
            if sim.player_policy().has_player_bonuses() {
                27
            } else if sim.player_policy() == OriginalExecutionProfile::PlayerDemonArmorV1 {
                26
            } else if sim.player_policy() == OriginalExecutionProfile::PlayerDemonPickupsV1 {
                25
            } else if sim.player_policy() == OriginalExecutionProfile::PlayerDemonWeaponsV1 {
                24
            } else if sim.player_policy() == OriginalExecutionProfile::PlayerDemonPistolV1 {
                23
            } else if sim.original_player.is_some() {
                22
            } else {
                21
            }
        }
    };
    // Versions18/19 explicitly compose the untyped static-sector field layout.
    let layout = if matches!(version, 18 | 19) {
        3
    } else if matches!(version, 20..=27) {
        17
    } else {
        version
    };
    field(
        &mut fields,
        "profile",
        (if matches!(version, 21..=27) {
            sim.player_policy().wire_id()
        } else {
            version
        })
        .to_le_bytes(),
    );
    if matches!(version, 21..=27) {
        field(
            &mut fields,
            "registry.schema",
            crate::ORIGINAL_REGISTRY_SCHEMA,
        );
        field(
            &mut fields,
            "context.schema",
            sim.player_policy().context_schema(),
        );
    }
    field(&mut fields, "paused", [u8::from(sim.paused)]);
    let [p, m] = sim.rng.indices();
    field(&mut fields, "rng.gameplay", [p]);
    field(&mut fields, "rng.miscellaneous", [m]);
    if layout >= 4 {
        field(
            &mut fields,
            "actors.options",
            [
                sim.actor_options.skill as u8,
                0,
                u8::from(sim.actor_options.no_monsters),
            ],
        );
    }
    if let Some(stats) = sim.statistics {
        for (name, value) in [
            ("level.total_kills", stats.total_kills),
            ("level.total_items", stats.total_items),
            ("level.total_secrets", stats.total_secrets),
            (
                "level.single_player_kill_count",
                stats.single_player_kill_count,
            ),
        ] {
            field(&mut fields, name, value.to_le_bytes());
        }
    }
    field(
        &mut fields,
        "store.max_slots",
        sim.actors.max_slots.to_le_bytes(),
    );
    count(&mut fields, "store.slot_count", sim.actors.slots.len());
    field(&mut fields, "store.head", optional_id(sim.actors.head));
    field(&mut fields, "store.tail", optional_id(sim.actors.tail));
    let order = sim.actors.order().flat_map(id).collect::<Vec<_>>();
    field(&mut fields, "thinker.order", order);
    for (i, slot) in sim.actors.slots.iter().enumerate() {
        let prefix = format!("actor.{i}");
        field(
            &mut fields,
            format!("{prefix}.generation"),
            slot.generation.to_le_bytes(),
        );
        field(
            &mut fields,
            format!("{prefix}.retired"),
            [u8::from(slot.retired)],
        );
        field(
            &mut fields,
            format!("{prefix}.occupied"),
            [u8::from(slot.entry.is_some())],
        );
        if let Some(entry) = &slot.entry {
            let a = &entry.value;
            field(
                &mut fields,
                format!("{prefix}.pending_removal"),
                [u8::from(entry.pending)],
            );
            field(
                &mut fields,
                format!("{prefix}.previous"),
                optional_id(entry.prev),
            );
            field(
                &mut fields,
                format!("{prefix}.next"),
                optional_id(entry.next),
            );
            for (label, value) in [
                ("x", a.spec.position[0]),
                ("y", a.spec.position[1]),
                ("z", a.z),
                ("momx", a.spec.momentum[0]),
                ("momy", a.spec.momentum[1]),
                ("radius", a.spec.radius),
                ("height", a.spec.height),
                ("floor", a.floor),
                ("ceiling", a.ceiling),
            ] {
                field(
                    &mut fields,
                    format!("{prefix}.{label}"),
                    value.bits().to_le_bytes(),
                );
            }
            field(
                &mut fields,
                format!("{prefix}.angle"),
                a.spec.angle.to_le_bytes(),
            );
            field(&mut fields, format!("{prefix}.lastlook"), [a.lastlook]);
            if layout >= 2 {
                field(
                    &mut fields,
                    format!("{prefix}.flags"),
                    a.life
                        .map_or_else(|| crate::multisector::flags(a), |life| life.flags)
                        .to_le_bytes(),
                );
            }
            if layout >= 4 {
                life_fields(&mut fields, &prefix, a.life.expect("typed profile"));
            }
            if layout >= 5 {
                field(
                    &mut fields,
                    format!("{prefix}.threshold"),
                    a.life.unwrap().threshold.to_le_bytes(),
                );
            }
            if layout >= 9 {
                field(
                    &mut fields,
                    format!("{prefix}.movedir"),
                    [a.life.unwrap().movedir],
                );
                field(
                    &mut fields,
                    format!("{prefix}.movecount"),
                    a.life.unwrap().movecount.to_le_bytes(),
                );
            }
            if let Some(p) = sim.original_player {
                field(
                    &mut fields,
                    format!("{prefix}.player"),
                    [
                        if p.mo.is_some_and(|mo| {
                            usize::try_from(mo.slot()).ok() == Some(i)
                                && mo.generation() == slot.generation
                        }) {
                            0
                        } else {
                            u8::MAX
                        },
                    ],
                );
            }
            if layout >= 3 {
                let location = a.location.expect("M3b actor location");
                field(
                    &mut fields,
                    format!("{prefix}.momz"),
                    a.momz.bits().to_le_bytes(),
                );
                field(
                    &mut fields,
                    format!("{prefix}.subsector"),
                    location.subsector.to_le_bytes(),
                );
                field(
                    &mut fields,
                    format!("{prefix}.sector"),
                    location.sector.to_le_bytes(),
                );
            }
        }
    }
    if layout >= 2 {
        field(
            &mut fields,
            "spatial.link_order",
            sim.spatial
                .order
                .iter()
                .copied()
                .flat_map(id)
                .collect::<Vec<_>>(),
        );
    }
    if layout >= 3 {
        field(&mut fields, "world.blockmap_policy", [1]);
        field(
            &mut fields,
            "world.conservative_omissions",
            sim.world
                .conservative_omissions()
                .expect("M3b policy")
                .to_le_bytes(),
        );
        field(
            &mut fields,
            "sectors.count",
            (sim.sectors.len() as u32).to_le_bytes(),
        );
        for (i, sector) in sim.sectors.iter().enumerate() {
            field(
                &mut fields,
                format!("sector.{i}.floor"),
                sector.floor.bits().to_le_bytes(),
            );
            field(
                &mut fields,
                format!("sector.{i}.ceiling"),
                sector.ceiling.bits().to_le_bytes(),
            );
            let order = sim
                .spatial
                .order
                .iter()
                .copied()
                .filter(|id| {
                    crate::lifecycle::in_sector_list(sim.actors.get(*id).expect("linked actor"))
                })
                .filter(|id| {
                    sim.actors
                        .get(*id)
                        .expect("live spatial identity")
                        .location
                        .expect("M3b location")
                        .sector
                        == i as u16
                })
                .flat_map(id)
                .collect::<Vec<_>>();
            field(&mut fields, format!("sector.{i}.actors"), order);
            if matches!(layout, 6 | 8..=17) {
                field(
                    &mut fields,
                    format!("sector.{i}.soundtarget"),
                    optional_id(sim.sound_targets[i]),
                );
            }
        }
    }
    for i in 0..4 {
        field(
            &mut fields,
            format!("player.{i}.actor"),
            optional_id(sim.bindings[i]),
        );
        let c = sim.commands[i];
        field(
            &mut fields,
            format!("player.{i}.forward"),
            [c.forward as u8],
        );
        field(&mut fields, format!("player.{i}.side"), [c.side as u8]);
        field(
            &mut fields,
            format!("player.{i}.angle_turn"),
            c.angle_turn.to_le_bytes(),
        );
        field(&mut fields, format!("player.{i}.buttons"), [c.buttons]);
    }
    if matches!(layout, 8..=17) && !matches!(version, 22..=27) {
        for (i, p) in sim.perception_players.iter().enumerate() {
            field(
                &mut fields,
                format!("perception.player.{i}.active"),
                [u8::from(p.active)],
            );
            field(
                &mut fields,
                format!("perception.player.{i}.health"),
                p.health.to_le_bytes(),
            );
            field(
                &mut fields,
                format!("perception.player.{i}.actor"),
                optional_id(p.actor),
            );
        }
    }
    if let Some(p) = sim.original_player {
        field(&mut fields, "original_player.0.mo", optional_id(p.mo));
        field(
            &mut fields,
            "original_player.0.health",
            p.health.to_le_bytes(),
        );
        field(
            &mut fields,
            "original_player.0.state",
            [u8::from(p.state == crate::PlayerBodyState::Dead)],
        );
        field(
            &mut fields,
            "original_player.0.attacker",
            optional_id(p.attacker),
        );
        field(
            &mut fields,
            "original_player.0.damage_count",
            p.damage_count.to_le_bytes(),
        );
        field(
            &mut fields,
            "original_player.0.frags",
            p.frags.to_le_bytes(),
        );
    }
    if version == 23 {
        pistol_fields(
            &mut fields,
            sim.original_player
                .and_then(|p| p.weapon.and_then(|w| w.pistol())),
        );
    }
    if matches!(version, 24..=27) {
        pack_fields(
            &mut fields,
            sim.original_player
                .and_then(|p| p.weapon.and_then(|w| w.pack())),
        );
    }
    if matches!(version, 25..=27) {
        let state = sim.original_player.and_then(|p| p.pickups);
        field(
            &mut fields,
            "original_player.0.pickups.present",
            [u8::from(state.is_some())],
        );
        if let Some(p) = state {
            field(
                &mut fields,
                "original_player.0.pickups.bonus_count",
                p.bonus_count.to_le_bytes(),
            );
            field(
                &mut fields,
                "original_player.0.pickups.item_count",
                p.item_count.to_le_bytes(),
            );
            field(
                &mut fields,
                "original_player.0.pickups.message",
                [p.message as u8],
            );
        }
    }
    if matches!(version, 26 | 27) {
        if let Some(armor) = sim.original_player.and_then(|p| p.armor) {
            field(
                &mut fields,
                "original_player.0.armor.type",
                [armor.kind.wire_id()],
            );
            field(
                &mut fields,
                "original_player.0.armor.points",
                armor.points.to_le_bytes(),
            );
        }
    }
    if layout == 6 {
        weapon_fields(&mut fields, sim.weapon_player.as_ref());
    }
    for (prefix, events) in [
        ("events.last", &sim.events),
        ("events.pending", &sim.pending),
    ] {
        count(&mut fields, &format!("{prefix}.count"), events.len());
        for (i, event) in events.iter().enumerate() {
            field(&mut fields, format!("{prefix}.{i}"), event_bytes(event));
        }
    }
    Snapshot {
        version,
        tic: sim.tic,
        state: fields,
        map: Arc::clone(&sim.map_fields),
    }
}

pub(crate) fn map_fields(map: &Map) -> Vec<StateField> {
    let mut fields = Vec::new();
    let mut b = Vec::new();
    for t in map.things() {
        for n in [t.position.x, t.position.y, t.angle, t.kind] {
            b.extend(n.to_le_bytes());
        }
        b.extend(t.options.to_le_bytes());
    }
    field(&mut fields, "map.things", b);
    let mut b = Vec::new();
    for l in map.linedefs() {
        for n in l.vertices {
            b.extend(n.to_le_bytes());
        }
        b.extend(l.flags.to_le_bytes());
        b.extend(l.special.to_le_bytes());
        b.extend(l.tag.to_le_bytes());
        for side in l.sides {
            b.extend(side.unwrap_or(u16::MAX).to_le_bytes());
        }
    }
    field(&mut fields, "map.linedefs", b);
    let mut b = Vec::new();
    for s in map.sidedefs() {
        for n in s.offsets {
            b.extend(n.to_le_bytes());
        }
        for t in s.textures {
            b.extend(t.as_bytes());
        }
        b.extend(s.sector.to_le_bytes());
    }
    field(&mut fields, "map.sidedefs", b);
    let mut b = Vec::new();
    for v in map.vertices() {
        b.extend(v.x.to_le_bytes());
        b.extend(v.y.to_le_bytes());
    }
    field(&mut fields, "map.vertices", b);
    let mut b = Vec::new();
    for s in map.segs() {
        for n in s.vertices {
            b.extend(n.to_le_bytes());
        }
        for n in [s.angle, s.linedef, s.side] {
            b.extend(n.to_le_bytes());
        }
        b.extend(s.offset.to_le_bytes());
    }
    field(&mut fields, "map.segs", b);
    let mut b = Vec::new();
    for s in map.subsectors() {
        b.extend(s.seg_count.to_le_bytes());
        b.extend(s.first_seg.to_le_bytes());
    }
    field(&mut fields, "map.subsectors", b);
    let mut b = Vec::new();
    for n in map.nodes() {
        for v in [n.origin.x, n.origin.y, n.delta.x, n.delta.y] {
            b.extend(v.to_le_bytes());
        }
        for bounds in n.bounds {
            for v in bounds {
                b.extend(v.to_le_bytes());
            }
        }
        for child in n.children {
            let v = match child {
                BspChild::Node(v) => v,
                BspChild::Subsector(v) => v | 0x8000,
            };
            b.extend(v.to_le_bytes());
        }
    }
    field(&mut fields, "map.nodes", b);
    let mut b = Vec::new();
    for s in map.sectors() {
        for v in s.heights {
            b.extend(v.to_le_bytes());
        }
        for f in s.flats {
            b.extend(f.as_bytes());
        }
        for v in [s.light, s.special, s.tag] {
            b.extend(v.to_le_bytes());
        }
    }
    field(&mut fields, "map.sectors", b);
    field(&mut fields, "map.reject", map.reject().to_vec());
    let b = map
        .blockmap()
        .words()
        .iter()
        .flat_map(|v| v.to_le_bytes())
        .collect::<Vec<_>>();
    field(&mut fields, "map.blockmap.words", b);
    let mut b = Vec::new();
    for r in map.blockmap().cell_ranges() {
        b.extend((r.start as u32).to_le_bytes());
        b.extend((r.end as u32).to_le_bytes());
    }
    field(&mut fields, "map.blockmap.cell_ranges", b);
    fields
}

// Explicit profile-4 encoding. Older versions never call these helpers.
fn action_bytes(b: &mut Vec<u8>, action: crate::ActorAction) {
    use crate::{ActorAction::*, ProbeAction};
    match action {
        None => b.push(0),
        Original(id) => {
            b.push(1);
            b.extend(id.0.to_le_bytes());
        }
        Probe(probe) => {
            b.push(2);
            match probe {
                ProbeAction::Random => b.push(0),
                ProbeAction::Enter(state) => {
                    b.push(1);
                    b.extend(state.0.to_le_bytes());
                }
                ProbeAction::SpawnTarget(ty) => {
                    b.push(2);
                    b.extend(ty.0.to_le_bytes());
                }
                ProbeAction::RemoveSelf => b.push(3),
                ProbeAction::RemoveTarget => b.push(4),
                ProbeAction::TargetSelf => b.push(5),
            }
        }
    }
}
fn state_event_bytes(b: &mut Vec<u8>, event: &crate::ActorStateEvent) {
    use crate::ActorStateEvent::*;
    match event {
        Initialized { actor, actor_type } => {
            b.push(0);
            b.extend(id(*actor));
            b.extend(actor_type.0.to_le_bytes());
        }
        Entered { actor, state } => {
            b.push(1);
            b.extend(id(*actor));
            b.extend(state.0.to_le_bytes());
        }
        Action { actor, action } => {
            b.push(2);
            b.extend(id(*actor));
            action_bytes(b, *action);
        }
        Sound { actor, sound } => {
            b.push(3);
            b.extend(optional_id(*actor));
            b.extend(sound.to_le_bytes());
        }
        Target { actor, target } => {
            b.push(4);
            b.extend(id(*actor));
            b.extend(optional_id(*target));
        }
        Death(actor) => {
            b.push(5);
            b.extend(id(*actor));
        }
        TargetUnavailable(actor) => {
            b.push(6);
            b.extend(id(*actor));
        }
        Random { actor, value } => {
            b.push(7);
            b.extend(id(*actor));
            b.push(*value);
        }
    }
}
