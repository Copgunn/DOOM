#!/usr/bin/env python3
"""Independent compiled-C identity observation; never reads Rust execution output."""
import argparse
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path
import generate_m3c as legacy

ROOT, SOURCE = legacy.ROOT, legacy.SOURCE
FLAGS = ['-std=gnu89', '-O0', '-Wall', '-Wextra', '-Wno-unused-const-variable', '-Werror', '-fno-strict-aliasing']
SANITIZER_FLAGS = ['-fsanitize=address,undefined', '-fno-sanitize-recover=all']


def observe(sanitize):
    code = ['#include <stdio.h>', '#include <stdlib.h>', '#include <limits.h>', '#include "info.c"']
    code += [f'void {n}(void* unused){{(void)unused;abort();}}' for n in legacy.ACTIONS[1:]]
    code += ['typedef char int_is_32[(sizeof(int)==4 && CHAR_BIT==8)?1:-1];']
    code += ['const char* action_name(state_t* s){if(!s->action.acp1)return "NULL";']
    code += [f'if(s->action.acp1=={n})return "{n}";' for n in legacy.ACTIONS[1:]]
    code += ['abort();}', 'int main(void){puts("DOOM-IDENTITY-v1");']
    code += ['printf("counts,%d,%d,%d\\n",NUMMOBJTYPES,NUMSTATES,NUMSPRITES);']
    for name in legacy.TYPE_NAMES:
        fields = ','.join('t->' + field for field in legacy.FIELDS)
        code += [f'{{mobjinfo_t* t=&mobjinfo[{name}];printf("type,%d,{name}' + ',%d' * 23 + f'\\n",{name},{fields});}}']
    for name in legacy.STATE_NAMES:
        code += [f'{{state_t* s=&states[{name}];if(s->frame<INT_MIN||s->frame>INT_MAX||s->tics<INT_MIN||s->tics>INT_MAX||s->misc1<INT_MIN||s->misc1>INT_MAX||s->misc2<INT_MIN||s->misc2>INT_MAX)abort();printf("state,%d,{name},%d,%ld,%ld,%s,%d,%ld,%ld\\n",{name},s->sprite,s->frame,s->tics,action_name(s),s->nextstate,s->misc1,s->misc2);}}']
    for name in legacy.SPRITE_NAMES:
        code += [f'printf("sprite,%d,{name},%s\\n",{name},sprnames[{name}]);']
    code += ['return 0;}']
    flags = list(FLAGS)
    if sanitize:
        flags += SANITIZER_FLAGS
    with tempfile.TemporaryDirectory(prefix='doom-identity-') as tmp:
        src, binary = Path(tmp) / 'observe.c', Path(tmp) / 'observe'
        src.write_text('\n'.join(code))
        subprocess.run(['cc', *flags, '-I' + str(SOURCE), str(src), '-o', str(binary)], check=True)
        return subprocess.check_output([str(binary)])


def constants():
    # Runtime constants derive declaration order; C fixture observes actual enum symbols.
    result = ['// Source identity constants; GPL-2.0-only. Generated by m3f4_reference.py.', '#![allow(missing_docs)]']
    for ty, names in [('OriginalActorType', legacy.TYPE_NAMES), ('OriginalState', legacy.STATE_NAMES), ('OriginalSprite', legacy.SPRITE_NAMES)]:
        result += [f'impl super::{ty} {{']
        result += [f'    pub const {name}: Self = Self({i});' for i, name in enumerate(names)]
        result += ['}']
    return ('\n'.join(result) + '\n').encode()


def run(check, sanitize):
    data = observe(False)
    if sanitize:
        assert observe(True) == data, 'sanitized identity observation differs'
    outputs = {'tests/reference/m3f4_identities.csv': data,
               'crates/doom-sim/src/identity/names.rs': constants()}
    sources = sorted(SOURCE.glob('*.h')) + [SOURCE / 'info.c']
    inputs = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sources}
    for name in ['tools/reference/m3f4_reference.py', 'tools/reference/generate_m3c.py']:
        inputs[name] = hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
    provenance = {'schema': 'DOOM-IDENTITY-v1', 'source_revision': 'a77dfb96cb91780ca334d0d4cfd86957558007e0',
                  'flags': FLAGS, 'sanitizer_flags': SANITIZER_FLAGS,
                  'counts': {'types': 137, 'states': 967, 'sprites': 138, 'non_null_action_symbols': 74},
                  'inputs_sha256': inputs, 'outputs_sha256': {n: hashlib.sha256(b).hexdigest() for n, b in outputs.items()},
                  'scope': 'Metadata only. Original enum values and info.c initializers; action stubs abort, pointer equality yields symbols, no action ordinal or behavior claim. C long fields use matching formats and i32 range checks. GNU89 host ABI; no Rust execution output.'}
    outputs['tests/reference/m3f4_provenance.json'] = (json.dumps(provenance, indent=2) + '\n').encode()
    for name, data in outputs.items():
        path = ROOT / name
        if check:
            assert path.read_bytes() == data, name
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f'{"Checked" if check else "Generated"} DOOM-IDENTITY-v1: 137 types, 967 states, 138 sprites; sanitized={sanitize}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--sanitize', action='store_true')
    args = parser.parse_args()
    run(args.check, args.sanitize)
